package ru.tsu.tpm.vacancyparser.common;

import java.time.Duration;
import java.util.List;

/**
 * Результат замера одной операции: значение операции плюс статистика по повторам.
 *
 * <p>Одиночный замер на JVM недействителен — первый прогон измеряет интерпретацию, а не
 * скомпилированный код. Поэтому результат содержит и «холодный» прогон отдельно, и статистику по
 * прогретым повторам, по которой принимается решение о разнице вариантов.
 *
 * @param <T>     тип результата измеряемой операции
 * @param result  значение, которое вернула операция (последний повтор). Хранится намеренно:
 *                во-первых, это проверка корректности (варианты обязаны совпасть), во-вторых,
 *                защита от мёртвой оптимизации — JIT не выбрасывает вычисление, чей результат
 *                используется
 * @param cold    «холодный», самый первый прогон: он и является прогревочным и в статистику не
 *                входит, но печатается отдельно как иллюстрация эффекта JIT
 * @param average среднее арифметическое по повторам
 * @param min     минимальное время повтора (лучший случай: внешние помехи сказались меньше всего)
 * @param max     максимальное время повтора
 * @param warmupRuns сколько прогонов ушло на прогрев
 * @param repeats времена отдельных повторов в порядке выполнения
 */
public record TimingResult<T>(
        T result,
        Duration cold,
        Duration average,
        Duration min,
        Duration max,
        int warmupRuns,
        List<Duration> repeats) {

    public TimingResult {
        repeats = List.copyOf(repeats);
    }

    /** Число учтённых повторов (без прогрева). */
    public int repeatCount() {
        return repeats.size();
    }

    /**
     * Разброс повторов: {@code max - min}.
     *
     * <p>Печатается отдельно, потому что без него нельзя судить, значима ли разница между
     * вариантами: если разброс одного варианта перекрывает разницу между вариантами, вывод
     * «быстрее в 1.05 раза» ничего не значит.
     */
    public Duration spread() {
        return max.minus(min);
    }

    /**
     * Разбросались ли повторы так, что средние нельзя считать различимыми.
     *
     * <p>Критерий простой и намеренно консервативный: интервалы {@code [min, max]} двух замеров
     * пересекаются. Тогда ни один из вариантов нельзя назвать быстрее — разница укладывается в
     * шум планировщика.
     */
    public boolean overlaps(TimingResult<?> other) {
        return min.compareTo(other.max) <= 0 && other.min.compareTo(max) <= 0;
    }
}
