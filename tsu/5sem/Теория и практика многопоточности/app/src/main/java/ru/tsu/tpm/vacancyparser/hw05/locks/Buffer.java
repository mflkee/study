package ru.tsu.tpm.vacancyparser.hw05.locks;

/**
 * Контракт ёмкостного буфера, общий для обеих реализаций: явной блокировки
 * ({@link BoundedBuffer}) и монитора ({@link MonitorBuffer}).
 *
 * <p>Интерфейс существует не «для красоты»: сравнение производительности имеет смысл только тогда,
 * когда обе реализации обязаны удовлетворять одному и тому же набору проверок. Если бы у каждой был
 * свой набор методов, можно было бы сравнить быстрое решение с неправильным. Поэтому инвариантные
 * тесты и нагрузочный прогон написаны против интерфейса, а не против конкретного класса.
 *
 * <p>Операции не объявляют {@code InterruptedException}: прерывание обрабатывается внутри
 * (блокировка освобождается, признак прерывания восстанавливается) и сообщается наружу как
 * {@link BufferOperationException} с причиной {@code INTERRUPTED}. Так вызывающий код не может
 * случайно «проглотить» прерывание, а признак остаётся выставленным.
 *
 * @param <T> тип элемента
 */
public interface Buffer<T> {

    /** Срок ожидания по умолчанию для операций без явного тайм-аута. */
    long DEFAULT_TIMEOUT_MILLIS = 10_000L;

    /**
     * Добавить элемент, дождавшись свободного места.
     *
     * @throws BufferOperationException если время вышло, буфер закрыт или поток прерван
     */
    void put(T item);

    /**
     * Извлечь элемент, дождавшись его появления.
     *
     * @throws BufferOperationException если время вышло, буфер закрыт или поток прерван
     */
    T take();

    /**
     * Попытка добавить элемент с ограничением по времени.
     *
     * @return {@code false}, если место не освободилось за отведённое время
     */
    boolean offer(T item, long timeoutMillis);

    /**
     * Попытка извлечь элемент с ограничением по времени.
     *
     * @return {@code null}, если элемент не появился за отведённое время
     */
    T poll(long timeoutMillis);

    /** Текущее число элементов. */
    int size();

    /** Ёмкость буфера. */
    int capacity();

    /** Буфер пуст. */
    boolean isEmpty();

    /** Буфер заполнен. */
    boolean isFull();

    /**
     * Закончить работу: все ожидающие обязаны выйти из ожидания и завершиться.
     *
     * <p>Это как раз тот случай, когда {@code signalAll()} обязателен: состояние изменилось для
     * всех ожидающих сразу, адресного «одного» здесь нет.
     */
    void close();

    /** Закрыт ли буфер. */
    boolean isClosed();
}
