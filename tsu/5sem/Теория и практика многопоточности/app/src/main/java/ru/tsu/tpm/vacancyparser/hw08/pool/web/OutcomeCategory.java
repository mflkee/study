package ru.tsu.tpm.vacancyparser.hw08.pool.web;

/**
 * Категория исхода запроса.
 *
 * <p>Ключевое различие: ответ с неуспешным кодом ({@code 404}, {@code 5xx}) — это <b>полученный
 * ответ</b>, а не сетевая ошибка. Ошибка транспорта (не подключиться, не разрешить имя), таймаут и
 * прерывание — отдельные категории, потому что лечатся по-разному и по-разному попадают в сводку.
 */
public enum OutcomeCategory {

    /** Сервер ответил — с любым статус-кодом, в том числе неуспешным. */
    RESPONSE("получен ответ"),

    /** Сервер не ответил дольше заданного таймаута. */
    TIMEOUT("таймаут"),

    /** Соединение не установлено или имя не разрешено. */
    NETWORK_ERROR("сетевая ошибка"),

    /** Задача прервана во время ожидания. */
    INTERRUPTED("прерывание"),

    /** Задача не принята к выполнению (некорректный адрес и т.п.). */
    REJECTED("отказ в выполнении");

    private final String label;

    OutcomeCategory(String label) {
        this.label = label;
    }

    /** Как категория называется в выводе и отчёте. */
    public String label() {
        return label;
    }
}
