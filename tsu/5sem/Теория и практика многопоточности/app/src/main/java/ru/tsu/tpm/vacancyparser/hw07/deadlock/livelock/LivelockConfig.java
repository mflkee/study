package ru.tsu.tpm.vacancyparser.hw07.deadlock.livelock;

/**
 * Конфигурация сценария livelock.
 *
 * <p>Различие — в правиле разрешения столкновения. Симметричное уступание (обе стороны одновременно
 * уступают друг другу) не даёт прогресса; детерминированный порядок (одна сторона по очереди получает
 * ресурс) прогресс даёт. Это ровно разница между явлением и его предотвращением.
 */
public enum LivelockConfig {

    /** Симметричное уступание: каждый раз оба уступают, успешных итераций нет. */
    LIVELOCK("симметричное уступание (livelock)"),

    /** Детерминированный порядок: столкновения разрешаются по очереди, прогресс есть. */
    NORMAL("детерминированный порядок (норма)");

    private final String label;

    LivelockConfig(String label) {
        this.label = label;
    }

    /** Как конфигурация называется в выводе. */
    public String label() {
        return label;
    }
}
