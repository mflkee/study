package ru.tsu.tpm.vacancyparser.hw12.collections.events;

/**
 * Тип события системы кэша.
 *
 * <p>Набор намеренно узкий: по нему видно, что происходило с кэшем, и его удобно считать в
 * {@code ConcurrentHashMap<EventType, LongAdder>}. Расширять перечисление «на будущее» не нужно —
 * каждое значение обязано использоваться.
 */
public enum EventType {

    /** Данные взяты из кэша без обращения к источнику. */
    CACHE_HIT("попадание"),

    /** Данных в кэше не было, потребовалась загрузка. */
    CACHE_MISS("промах"),

    /** Значение загружено и положено в кэш. */
    CACHE_LOAD("загрузка"),

    /** Запись вытеснена из-за ограничения ёмкости. */
    CACHE_EVICT("вытеснение"),

    /** Запись удалена по истечении срока жизни. */
    CACHE_EXPIRE("истечение срока"),

    /** Карточка сохранена в кэш напрямую (не через загрузку). */
    VACANCY_SAVED("сохранение");

    private final String label;

    EventType(String label) {
        this.label = label;
    }

    /** Русское название для отчёта. */
    public String label() {
        return label;
    }
}
