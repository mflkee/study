package ru.tsu.tpm.vacancyparser.hw03.parallel;

import java.util.List;

/**
 * Результаты трёх операций, полученные в одном из вариантов исполнения.
 *
 * <p>Результаты не выбрасываются: они сравниваются между вариантами (параллельный обязан дать то же
 * самое, что последовательный) и печатаются в отчёте — по ним видно, что обе ветви действительно
 * что-то посчитали, а не были выброшены JIT как мёртвый код.
 *
 * @param evenCount число чётных элементов исходного списка
 * @param doubled   исходный список, каждый элемент которого умножен на 2; размер совпадает с
 *                  размером входа, и элемент с индексом {@code i} вдвое больше исходного
 * @param sum       сумма элементов исходного списка
 */
public record OperationResults(long evenCount, List<Integer> doubled, long sum) {

    public OperationResults {
        doubled = List.copyOf(doubled);
    }
}
