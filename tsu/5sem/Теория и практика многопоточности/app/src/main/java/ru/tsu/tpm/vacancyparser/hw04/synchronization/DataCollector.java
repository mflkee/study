package ru.tsu.tpm.vacancyparser.hw04.synchronization;

import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Objects;
import java.util.Set;
import java.util.concurrent.TimeUnit;

/**
 * Разделяемое состояние сбора: собранные элементы, счётчик обработанных и множество обработанных
 * ключей.
 *
 * <p><b>Единый владелец состояния.</b> Всё, что делят потоки, лежит в одном объекте, и доступ к
 * нему идёт только через его методы. Это делает инвариант
 * «размер списка = счётчик = число уникальных ключей» проверяемым в одном месте, а не собираемым
 * по разным классам.
 *
 * <p><b>Почему {@code synchronized} на методах, а не блок внутри.</b> Требование задания —
 * защита именно через монитор, и метод-монитор даёт её без возможности «забыть захватить» или не
 * отпустить в {@code finally}. Заодно это делает защиту видимой в сигнатуре: {@code javap}
 * показывает модификатор {@code synchronized} на каждом публичном методе, то есть проверяемо, а не
 * «на слово».
 *
 * <p><b>Про ожидание.</b> Условие ожидания проверяется только в цикле {@code while}, никогда в
 * {@code if}. Причина: {@code wait()} освобождает монитор, поэтому между проверкой условия и
 * засыпанием есть окно, в которое другой поток может изменить состояние и отправить уведомление —
 * уведомление до засыпания теряется, и поток спит вечно (классический lost wakeup). С циклом поток
 * после пробуждения просто перепроверяет условие. Вторая причина — уведомление не адресное: поток
 * может проснуться «не от того события», и тогда он обязан вернуться в ожидание.
 *
 * <p><b>Про два вида уведомления.</b> {@code notify()} применяется там, где состояние изменилось
 * ровно для одного ожидающего: пришёл один элемент — работу может продолжить ровно один
 * потребитель. {@code notifyAll()} — там, где изменение касается всех ожидающих сразу: набор данных
 * готов целиком, и каждый ожидающий обязан перепроверить своё условие. Первое дешевле, второе
 * безопаснее; оба нужны, и их разное поведение проверяется тестом.
 *
 * <p><b>Ограничение, которое важно понимать.</b> Оба условия ожидания — «данные готовы» и «появился
 * элемент» — живут на одном мониторе, то есть в одном множестве ожидающих. {@code notify()} не
 * адресный: разбудив одного ожидающего, он может разбудить того, чьё условие всё ещё ложно (цикл
 * заставит его заснуть снова), а нужный ожидающий останется спать до следующего уведомления. Поэтому
 * смешивать оба вида ожидающих на одном экземпляре нельзя: в демонстрации и тестах они
 * используются в раздельных сценариях. Именно это ограничение снимает {@code Condition} в ДЗ 5,
 * где на одну блокировку можно завести несколько независимых множеств ожидающих.
 */
public class DataCollector {

    private final List<Item> collected = new ArrayList<>();
    private final Set<String> processedKeys = new LinkedHashSet<>();

    private long processedCount;
    private boolean ready;

    /** Сколько раз поток просыпался и не находил работы — цена лишних пробуждений. */
    private long wastedWakeups;

    // ------------------------------------------------------------------ наблюдаемое состояние

    /** Размер списка собранных элементов. */
    public synchronized int collectedCount() {
        return collected.size();
    }

    /** Значение счётчика обработанных элементов. */
    public synchronized long processedCount() {
        return processedCount;
    }

    /** Число уникальных обработанных ключей. */
    public synchronized int processedKeyCount() {
        return processedKeys.size();
    }

    /** Копия списка собранных элементов — чтобы вызывающий код не мог изменить состояние в обход защит. */
    public synchronized List<Item> collected() {
        return List.copyOf(collected);
    }

    /** Готов ли набор данных целиком. */
    public synchronized boolean isReady() {
        return ready;
    }

    /** Сколько раз ожидающий просыпался впустую: разбудили, а работы для него не нашлось. */
    public synchronized long wastedWakeups() {
        return wastedWakeups;
    }

    /**
     * Проверить согласованность трёх величин: размер списка, счётчик и число уникальных ключей.
     *
     * <p>Инвариант держится, когда сбор идёт через {@link #collectItem(Item)} — именно он
     * учитывает элемент во всех трёх местах одной критической секцией. Вызов
     * {@link #incrementProcessed()} в одиночку счётчик увеличивает, но список и ключи не трогает,
     * поэтому нарушение инварианта означает, что состояние меняли в обход сбора.
     *
     * @return описания расхождений; пустой список — состояние согласовано
     */
    public synchronized List<String> invariantViolations() {
        List<String> violations = new ArrayList<>();
        int items = collected.size();
        int keys = processedKeys.size();

        if (items != processedCount) {
            violations.add("размер списка " + items + " не равен счётчику " + processedCount);
        }
        if (keys != items) {
            violations.add("число уникальных ключей " + keys + " не равно размеру списка " + items);
        }
        if (processedCount != keys) {
            violations.add("счётчик " + processedCount + " не равен числу уникальных ключей " + keys);
        }
        return List.copyOf(violations);
    }

    // ------------------------------------------------------------------ методы из текста задания

    /**
     * Принять элемент к обработке.
     *
     * <p>Проверка «уже обработан» и запись выполняются одной критической секцией, поэтому два
     * потока, одновременно предъявивших один ключ, не могут оба решить, что элемент новый: один
     * примет его, второй получит {@code false} и не изменит состояние.
     *
     * <p>Приём элемента учитывается счётчиком обработанных: именно поэтому три величины — размер
     * списка, счётчик и число уникальных ключей — согласованы между собой.
     *
     * @return {@code true}, если элемент новый и принят; {@code false}, если ключ уже обрабатывался
     */
    public synchronized boolean collectItem(Item item) {
        Objects.requireNonNull(item, "элемент обязателен");

        if (processedKeys.contains(item.key())) {
            return false;
        }
        collected.add(item);
        processedKeys.add(item.key());
        processedCount++;

        // Уведомление идёт после изменения состояния и в той же критической секции: иначе
        // разбуженный поток успел бы перепроверить условие до того, как изменение стало видимым.
        // Пришёл один элемент — продолжить работу может ровно один потребитель, поэтому notify().
        notify();
        return true;
    }

    /**
     * Увеличить счётчик обработанных элементов на единицу.
     *
     * <p>Отдельный примитив для нагрузки «N потоков × M увеличений»: он позволяет измерять именно
     * потерю обновлений счётчика, не примешивая к этому работу со списком и множеством.
     */
    public synchronized void incrementProcessed() {
        processedCount++;
    }

    /**
     * Проверить, обрабатывался ли ключ.
     *
     * <p>Метод атомарен на момент запроса, но это не даёт права действовать по его ответу
     * «проверить, затем обработать» из двух отдельных критических секций: между проверкой и
     * обработкой состояние может измениться. Правильный порядок — атомарный
     * {@link #collectItem(Item)}, который сам проверяет и помечает.
     */
    public synchronized boolean isAlreadyProcessed(String key) {
        return processedKeys.contains(key);
    }

    // ------------------------------------------------------------------ ожидание и уведомление

    /**
     * Объявить набор данных готовым и разбудить всех ожидающих.
     *
     * <p>Используется {@code notifyAll()}, потому что изменение касается всех: каждый ожидающий
     * проверял своё условие и обязан перепроверить его после смены состояния.
     */
    public synchronized void markReady() {
        ready = true;
        notifyAll();
    }

    /**
     * Дождаться готовности данных — ожидание без таймаута.
     *
     * <p>Без таймаута, чтобы поток действительно находился в состоянии {@code WAITING}, а не
     * {@code TIMED_WAITING}: это и есть «потоку нечего делать, он освобождает монитор и ждёт».
     * Гарантия завершения — не таймаут, а то, что уведомление обязательно придёт; демонстрация
     * дополнительно ограничена по времени снаружи.
     *
     * <p>Условие проверяется в цикле: после пробуждения состояние перепроверяется, и если
     * готовность ещё не наступила (разбудили не от того события), поток засыпает снова.
     */
    public synchronized void awaitReady() throws InterruptedException {
        while (!ready) {
            wait();
        }
    }

    /**
     * Дождаться готовности данных с ограничением по времени.
     *
     * @param timeoutMillis предел ожидания
     * @return {@code true}, если данные готовы; {@code false}, если время вышло
     */
    public synchronized boolean awaitReady(long timeoutMillis) throws InterruptedException {
        long deadline = System.nanoTime() + TimeUnit.MILLISECONDS.toNanos(timeoutMillis);
        while (!ready) {
            long remaining = deadline - System.nanoTime();
            if (remaining <= 0) {
                return false;
            }
            TimeUnit.NANOSECONDS.timedWait(this, remaining);
        }
        return true;
    }

    /**
     * Забрать один собранный элемент, дождавшись его появления.
     *
     * <p>Это вторая сторона того же ожидания: потребителю нечего делать, пока нет элементов, и
     * он ждёт в цикле, пока очередь не опустеет-перестанет быть пустой. Возвращает {@code null},
     * если элемент не появился за отведённое время.
     *
     * <p>Пробуждения, после которых работы не нашлось, считаются: по этому числу видно разницу
     * между {@code notify()} и {@code notifyAll()} — второе будит всех, и лишние просыпаются зря.
     */
    public synchronized Item takeItem(long timeoutMillis) throws InterruptedException {
        long deadline = System.nanoTime() + TimeUnit.MILLISECONDS.toNanos(timeoutMillis);
        while (collected.isEmpty()) {
            long remaining = deadline - System.nanoTime();
            if (remaining <= 0) {
                return null;
            }
            TimeUnit.NANOSECONDS.timedWait(this, remaining);
            if (collected.isEmpty() && System.nanoTime() < deadline) {
                wastedWakeups++;
            }
        }
        return collected.remove(0);
    }
}
