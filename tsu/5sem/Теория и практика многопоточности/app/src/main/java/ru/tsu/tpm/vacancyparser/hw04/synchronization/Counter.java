package ru.tsu.tpm.vacancyparser.hw04.synchronization;

/**
 * Счётчик, по которому сравниваются защищённый и незащищённый варианты работы с общим состоянием.
 *
 * <p>Вынесен в отдельный тип, потому что сравнить «синхронизированное против несинхронизированного»
 * на одном и том же классе с флагом внутри нельзя: требуемые методы {@link DataCollector} обязаны
 * быть настоящими {@code synchronized}-методами (это проверяется по модификатору в байт-коде), а
 * метод с флагом внутри такого модификатора уже не имеет. Переключается <b>стратегия защиты</b>, а
 * не код операции: нагрузка, число потоков и харнесс остаются одними и теми же.
 */
public interface Counter {

    /** Увеличить значение на единицу. */
    void increment();

    /** Текущее значение. */
    long value();
}
