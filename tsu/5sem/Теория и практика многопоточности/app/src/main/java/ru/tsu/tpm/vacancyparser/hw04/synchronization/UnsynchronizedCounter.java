package ru.tsu.tpm.vacancyparser.hw04.synchronization;

/**
 * Тот же счётчик без защиты — эталон для сравнения и демонстрации дефекта.
 *
 * <p>Операция {@code value++} состоит из трёх шагов: прочитать, увеличить, записать. Между чтением
 * и записью другой поток успевает прочитать то же самое значение, и одно из обновлений теряется —
 * это классическая гонка данных. Класс существует только ради сравнения: он показывает, что даёт
 * синхронизация, и сколько она стоит по времени.
 *
 * <p>Никогда не используется как рабочая реализация: результат зависит от планировщика и от машины,
 * то есть не воспроизводим по определению.
 */
public final class UnsynchronizedCounter implements Counter {

    private long value;

    @Override
    public void increment() {
        value++;
    }

    @Override
    public long value() {
        return value;
    }
}
