//! Имитация датчиков 4–20 мА (режим `sim`).
//!
//! # Зачем симуляция
//!
//! Половину приложений — RTU-slave по RS-485, калибровку, сценарии обучения —
//! можно разрабатывать и отлаживать **без единого датчика**.
//! Для этого бэкенд `SimAdc` подменяет реальный АЦП (см. `adc_backend`).
//!
//! # Как «рисуются» показания
//!
//! Никакого АЦП не нужно: каждый канал выдаёт **синусоиду тока** в диапазоне
//! ~4.5..19.5 мА с собственным периодом и фазой. Код АЦП считается из
//! «идеальной» калибровки (`Calibration::ideal().code_for(мА)`), так что
//! показания в ИВК будут «живыми» и похожими на реальные измерения.
//!
//! Зачем разные периоды/фазы: в ИВК (или TUI стенде) сразу видно «24 разных
//! датчика», а не одну и ту же кривую на всех каналах.

#![cfg_attr(not(feature = "sim"), allow(dead_code))]

use std::f64::consts::PI;

use ai32_core::Calibration;

use super::adc_backend::AdcBackend;

/// «Виртуальный модуль аналогового ввода».
pub struct SimAdc;

impl SimAdc {
    pub fn new() -> Self {
        Self
    }
}

impl AdcBackend for SimAdc {
    fn read_code(&mut self, channel: u8) -> u32 {
        let ch = channel as f64;
        // Текущее время в секундах. esp_timer_get_time() возвращает мкс с
        // момента старта; это глобальный счётчик FreeRTOS — работает и без
        // железа, поэтому симуляция «живёт во времени» очень естественно.
        let t_sec = unsafe { esp_idf_sys::esp_timer_get_time() } as f64 / 1_000_000.0;

        // У каждого канала свой период и фаза — «индивидуальные датчики».
        // Период от 8 до 8+23*3.2 ≈ 82 с, фаза сдвигает кривую по времени.
        let period = 8.0 + ch * 3.2;
        let phase = ch * 1.7;

        // Синус в диапазоне 12 ± 7.2 мА → 4.8..19.2 мА (близко к реальным
        // 4–20 мА, но никогда не «сливается» с краями шкалы).
        let ma = 12.0 + 7.2 * (2.0 * PI * t_sec / period + phase).sin();

        // Код АЦП = «в каком коде при идеальной калибровке был бы этот ток».
        // Округляем до целого (АЦП выдаёт целое число кодов), не уходим в
        // минус (код не бывает отрицательным) и не выходим за 24 бита.
        let cal = Calibration::ideal();
        (cal.code_for(ma as f32).round().max(0.0) as u64)
            .min(0xFF_FFFF) as u32
    }
}