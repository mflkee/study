//! Общий интерфейс «источника кода АЦП».
//!
//! # Зачем он нужен
//!
//! Сканер каналов (главный поток в `main.rs`) не должен знать, откуда
//! приходят данные: от реальных 24-битных АЦП по SPI (фича `sim` **выключена**)
//! или от имитации (фича `sim` **включена** — режим по умолчанию).
//! Это классический приём **внедрения зависимости (интерфейс вместо класса)**:
//!
//! ```text
//!                 ┌──────────────────────┐
//!   код АЦП  ◄─── │ Box<dyn AdcBackend>   │
//!                 │   = реальный | sim    │
//!                 └──────────────────────┘
//!                     ▲                ▲
//!          AdsBackend (3×SPI)     SimAdc (синусоиды)
//! ```
//!
//! Благодаря этому Modbus-часть, калибровку и обучение можно разрабатывать
//! **без железа**: `cargo +esp check` собирает тот же код и с `sim`, и без.

/// Источник кодов АЦП. Каналы 0..=23: биты 3..4 выбирают один из трёх чипов
/// (CS0..CS2), биты 0..2 — канал внутри восьми (это делает сам бэкенд).
pub trait AdcBackend {
    /// Возвращает **«сырой»** 24-битный код АЦП для канала `channel` (0..=23).
    ///
    /// Код — это число из АЦП ДО всякой калибровки. Превращением кода в
    /// миллиамперы занимается уже `ai32-core` (`Calibration::current_ma`).
    /// Интерфейс возвращает `u32` — у 24-битного АЦП результат укладывается
    /// в диапазон `0..16_777_215`.
    fn read_code(&mut self, channel: u8) -> u32;
}