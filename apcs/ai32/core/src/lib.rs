//! AI-32 core — логика 24-канального модуля аналогового ввода 4–20 мА.
//!
//! # Что это за крейт
//!
//! Это «чистое ядро» модуля: **вся математика и весь протокол без железа**.
//! Здесь нет SPI, GPIO, NVS — только данные в оперативной памяти, формулы
//! калибровки и байты Modbus. Такой крейт можно собирать и тестировать
//! обычным `cargo test` на любом ПК.
//!
//! Разделение «core ↔ fw» — главный приём обучения на реальной задаче:
//!
//! | Крейт        | Что в нём                                      | Как проверяется        |
//! |--------------|------------------------------------------------|------------------------|
//! | `ai32-core`  | калибровка, каналы, карта регистров, CRC       | `cargo test` (unit)     |
//! | `ai32-fw`    | SPI, GPIO, АЦП ADS1256, RTU по RS-485, NVS     | `cargo +esp check`      |
//!
//! Прошивка использует core как **источник истины**: она вызывает
//! `register_map::dispatch`, `crc::verify_crc` — тот же код, что покрыт
//! тестами.
//!
//! # Как читать файлы
//!
//! Начинайте с самого «низа» — одного канала:
//!
//! 1. [`calib`] — как из кода АЦП получить ток в миллиамперах;
//! 2. [`channels`] — как хранится состояние 24 каналов;
//! 3. [`register_map`] — как каналы и калибровка видны по Modbus (FC01..FC06);
//! 4. [`crc`] — контрольная сумма кадров Modbus RTU.
//!
//! Каждый модуль написан так, что его можно прочитать сверху вниз, а тесты
//! под ним — это «проверка понимания»: разобрался в коде — поймёшь тест.

pub mod calib;
pub mod channels;
pub mod crc;
pub mod register_map;

// Короткие псевдонимы на верхнем уровне: `ai32_core::Calibration` вместо
