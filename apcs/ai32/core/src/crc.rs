//! CRC16 (Modbus RTU) — контрольная сумма кадров.
//!
//! # Зачем нужен CRC
//!
//! По RS-485 данные ходят по «шумным» проводам: помеха может перевернуть
//! бит. Чтобы отличить «плохой» кадр от «хорошего», к каждому кадру RTU
//! дописывают **контрольную сумму**, вычисленную по содержимому. Приёмник
//! пересчитывает её и сверяет: совпала — принять кадр, не совпала —
//! выбросить (и попросить повторить).
//!
//! # Что за алгоритм
//!
//! Modbus использует **CRC-16-IBM** (он же CRC-16/ARC): полином `0xA001`,
//! начальное значение `0xFFFF`. Реализация здесь — «бит за битом» (без
//! таблицы), это медленнее табличного варианта, но наглядно и коротко —
//! для обучения самое то.
//!
//! Специфические соглашения Modbus (их легко забыть, поэтому они ниже):
//!
//! - полином передаётся **отражённым** (`0xA001` вместо `0x8005`) — работаем
//!   с младшим битом, а не со старшим;
//! - **младший байт CRC в кадре идёт ПЕРВЫМ** (поэтому в `append_crc` сначала
//!   кладём `crc & 0xFF`, потом `crc >> 8`);
//! - CRC считается по `[адрес][PDU]` **без** самого поля CRC.

/// Вычисляет CRC-16 Modbus для буфера (адрес + PDU, без поля CRC).
pub fn crc16(buf: &[u8]) -> u16 {
    let mut crc: u16 = 0xFFFF; // стандартное начальное значение
    for &byte in buf {
        crc ^= byte as u16; // «подмешиваем» очередной байт
        for _ in 0..8 {
            // Каждый бит байта обрабатываем одинаково:
            if crc & 0x0001 != 0 {
                // Если вышел единичный бит — сдвиг и «сложение» с полиномом
                // (деление по модулю 2). Полином отражён: 0x8005 -> 0xA001.
                crc = (crc >> 1) ^ 0xA001;
            } else {
                // Нулевой бит — просто сдвиг.
                crc >>= 1;
            }
        }
    }
    crc
}

/// Приписывает CRC к кадру `[адрес][PDU]` → готовая RTU-посылка.
///
/// # Почему сначала младший байт
///
/// Спецификация Modbus RTU требует отправлять CRC **младшим байтом вперёд**
/// (в отличие от большинства других CRC-протоколов, где идёт старший).
/// Поэтому первым в кадр идёт `crc & 0xFF`, вторым — `crc >> 8`.
pub fn append_crc(frame: &[u8]) -> Vec<u8> {
    let crc = crc16(frame);
    let mut out = frame.to_vec();
    out.push((crc & 0xFF) as u8); // L-байт
    out.push((crc >> 8) as u8);   // H-байт
    out
}

/// Проверяет CRC у готового кадра `[адрес][PDU][CRC low][CRC high]`.
///
/// Принимает кадр целиком, отбрасывает два последних байта (поле CRC),
/// пересчитывает сумму и сверяется. Кадр короче 4 байт (адрес + функция +
/// CRC) просто не бывает — такие не принимаем.
pub fn verify_crc(frame: &[u8]) -> bool {
    if frame.len() < 4 {
        return false;
    }
    let body_len = frame.len() - 2;      // всё, кроме поля CRC
    let expected = crc16(&frame[..body_len]);
    // Поле CRC хранится как [lo][hi].
    let lo = frame[body_len] as u16;
    let hi = frame[body_len + 1] as u16;
    (lo | (hi << 8)) == expected
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn crc_known_vector() {
        // Эталонный пример из спецификации Modbus:
        //   01 03 00 00 00 0A  →  CRC = 0xC5CD
        // (т.е. в кадр лягут байты C5 CD — младший первым).
        let mut frame = vec![0x01, 0x03, 0x00, 0x00, 0x00, 0x0A];
        let crc = crc16(&frame);
        frame.push((crc & 0xFF) as u8);
        frame.push((crc >> 8) as u8);
        assert_eq!(frame, [0x01, 0x03, 0x00, 0x00, 0x00, 0x0A, 0xC5, 0xCD]);
        assert!(verify_crc(&frame));
    }

    #[test]
    fn crc_verify_detects_corruption() {
        // Перевернули один бит в кадре — CRC обязан стать невалидным.
        // Это и есть главный сценарий RTU: «сбитый» кадр не должен пройти.
        let mut frame = vec![0x01, 0x03, 0x00, 0x00, 0x00, 0x0A];
        let crc = crc16(&frame);
        frame.push((crc & 0xFF) as u8);
        frame.push((crc >> 8) as u8);
        assert!(verify_crc(&frame));
        frame[1] ^= 0x01; // флипнули байт функции
        assert!(!verify_crc(&frame));
        assert!(!verify_crc(&[0x01, 0x03])); // слишком короткий кадр
    }
}