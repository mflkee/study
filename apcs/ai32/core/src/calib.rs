//! Двухточечная калибровка одного канала.
//!
//! # Задача
//!
//! Датчик даёт ток 4–20 мА. Ток протекает через шунт 165 Ом (см.
//! `ai32/docs/`, раздел «Аналоговый тракт»), на шунте рождается напряжение,
//! АЦП (24-битный, например ADS1256) превращает его в код. Нужно из кода
//! получить ток обратно. Если бы шунт был ровно 165 Ом, а АЦП — идеальным,
//! хватило бы одной формулы. В жизни есть разброс допусков, поэтому модуль
//! **калибруют по двум точкам**.
//!
//! # Идея
//!
//! 1. Подаём на канал точный эталонный ток **4.000 мА** и запоминаем
//!    усреднённый «сырой» код АЦП `n4`;
//! 2. подаём **20.000 мА** — запоминаем `n20`;
//! 3. через две точки `(n4, 4)` и `(n20, 20)` проводим прямую — это и есть
//!    наша «шкала» кода в ток.
//!
//! ```text
//!   gain   = (I20 - I4) / (n20 - n4)   [мА на код]   — наклон прямой
//!   offset = I4 - gain * n4            [мА при коде 0] — сдвиг
//!   I      = gain * n + offset
//! ```
//!
//! Коэффициенты `gain`/`offset` хранятся в NVS (flash ESP32) отдельно для
//! каждого из 32 каналов (см. `ai32/fw/src/config_store.rs`).

/// Нижняя точка рабочей шкалы: 4.000 мА («ноль» измеряемой величины).
pub const I4_MA: f32 = 4.0;
/// Верхняя точка рабочей шкалы: 20.000 мА («максимум» измеряемой величины).
pub const I20_MA: f32 = 20.0;

/// Цена младшего разряда 24-битного АЦП (например ADS1256):
/// `LSB = диапазон / количество кодов = 5,12 В / 2^24 ≈ 0,305 мкВ`.
pub const ADC_LSB_V: f32 = 5.12 / 16_777_216.0;
/// Сопротивление измерительного шунта канала (Ом).
pub const SHUNT_OHM: f32 = 165.0;

/// Линейная калибровка канала: `gain` (мА/код) и `offset` (мА).
///
/// Применяется формулой `I = gain * code + offset` (см. `current_ma`).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Calibration {
    pub gain: f32,
    pub offset: f32,
}

impl Calibration {
    /// «Фабричная» идеальная калибровка — без реальных эталонных точек.
    ///
    /// Считается из закона Ома и цены разряда АЦП:
    /// напряжение на шунте `U = I * R`, АЦП даёт код `code = U / LSB`,
    /// значит `I = code * LSB / R`, т.е. `gain = LSB/R` мА/код (×1000 — это
    /// перевод амперов в миллиамперы), а смещение 0.
    pub fn ideal() -> Self {
        Self {
            gain: (ADC_LSB_V / SHUNT_OHM) * 1_000.0, // мА/код
            offset: 0.0,
        }
    }

    /// Калибровка по двум эталонным точкам (см. документацию модуля).
    ///
    /// `n4`/`n20` — «сырые» коды АЦП, усреднённые по N выборкам, на точных
    /// токах 4 мА и 20 мА. Возвращает `None`, если точки совпадают — тогда
    /// формула `(I20-I4)/(n20-n4)` дала бы деление на ноль.
    ///
    /// # Почему `Option`, а не паника
    ///
    /// Совпавшие точки — это ошибка измерения (например, на канал не подали
    /// разные токи). Задача калибровки — не уронить прошивку, а честно
    /// сообщить: «данные негодные, используйте идеальную калибровку».
    pub fn from_points(n4: f32, n20: f32) -> Option<Self> {
        // f32::EPSILON — наименьшая заметная разница для чисел ~1.0;
        // сравниваем НЕ с нулём, потому что коды большие (тысячи).
        if (n20 - n4).abs() < f32::EPSILON {
            return None;
        }
        let gain = (I20_MA - I4_MA) / (n20 - n4); // (20-4) мА / (n20-n4) кодов
        let offset = I4_MA - gain * n4;            // подгоняем прямую через точку 4 мА
        Some(Self { gain, offset })
    }

    /// Переводит сырой код АЦП в ток (мА) с учётом калибровки.
    ///
    /// Это и есть обратная задача модуля: из числа АЦП «сделать» миллиамперы.
    pub fn current_ma(&self, raw_code: f32) -> f32 {
        self.gain * raw_code + self.offset
    }

    /// Обратная функция: какой код АЦП соответствует току `current_ma`.
    ///
    /// Нужна в sim-режиме прошивки: там мы «хотим» показать, например,
    /// 12 мА, и должны выдать такой код, чтобы `current_ma` вернул 12.
    pub fn code_for(&self, current_ma: f32) -> f32 {
        if self.gain.abs() < f32::EPSILON {
            return 0.0; // защита от деления на (почти) ноль
        }
        (current_ma - self.offset) / self.gain
    }
}

impl Default for Calibration {
    /// По умолчанию — идеальная калибровка (завод выбрал «в среднем»).
    fn default() -> Self {
        Self::ideal()
    }
}

/// Удобная обёртка для целых кодов АЦП: `from_points(2_768_743, 13_843_714)`.
///
/// В прошивке коды приходят u32 (24 бита), поэтому отдельная функция от
/// `u32` — меньше `as f32` по месту вызова.
pub fn from_points(n4: u32, n20: u32) -> Option<Calibration> {
    Calibration::from_points(n4 as f32, n20 as f32)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Идеальные коды АЦП для идеальной калибровки.
    ///
    /// По закону Ома: при 4 мА на шунте 165 Ом падает 0.66 В, при 20 мА —
    /// 3.30 В. Код = напряжение / LSB (0.305 мкВ, 24 бита):
    ///   n(4 мА)  = 0.660 В / 0.305 мкВ = 2 162 688
    ///   n(20 мА) = 3.300 В / 0.305 мкВ = 10 813 440
    const N4_IDEAL: f32 = 0.660 / 0.000_000_305_175_781_25;
    const N20_IDEAL: f32 = 3.300 / 0.000_000_305_175_781_25;

    #[test]
    fn ideal_calibration_maps_code_to_current() {
        // Идеальная калибровка, поданная на ИДЕАЛЬНЫЕ коды, должна вернуть
        // ровно 4.0 и 20.0 мА. Это «самопроверка физики»: если падает —
        // где-то ошибка в константах (шунт/LSB).
        let cal = Calibration::ideal();
        let i4 = cal.current_ma(N4_IDEAL);
        let i20 = cal.current_ma(N20_IDEAL);
        assert!((i4 - 4.0).abs() < 1e-3, "i4 = {}", i4);
        assert!((i20 - 20.0).abs() < 1e-3, "i20 = {}", i20);
    }

    #[test]
    fn two_point_calibration_reproduces_reference_points() {
        // Калибровка «по двум точкам» обязана точно проходить через них же.
        let cal = Calibration::from_points(N4_IDEAL, N20_IDEAL).unwrap();
        assert!((cal.current_ma(N4_IDEAL) - 4.0).abs() < 1e-3);
        assert!((cal.current_ma(N20_IDEAL) - 20.0).abs() < 1e-3);
        // Внутри диапазона зависимость линейная: середина шкалы = 12 мА.
        let mid = (N4_IDEAL + N20_IDEAL) / 2.0;
        assert!((cal.current_ma(mid) - 12.0).abs() < 1e-2);
    }

    #[test]
    fn degenerate_points_return_none() {
        // Обе точки одинаковые → деление на ноль → честный `None`.
        assert!(Calibration::from_points(1000.0, 1000.0).is_none());
    }

    #[test]
    fn code_for_is_inverse_of_current() {
        // code_for и current_ma — взаимно обратные функции.
        let cal = Calibration::from_points(10_000.0, 40_000.0).unwrap();
        let code = cal.code_for(12.0);
        assert!((cal.current_ma(code) - 12.0).abs() < 1e-3);
    }

    #[test]
    fn out_of_range_extrapolates_linearly() {
        // За пределами 4..20 мА прямая не «ломается» — экстраполирует.
        // Это важно: ИВК должен видеть аварию (ток 3 мА или 22 мА) как
        // честное число, а не как «обрезку по шкале».
        let cal = Calibration::from_points(N4_IDEAL, N20_IDEAL).unwrap();
        assert!(cal.current_ma(N4_IDEAL - 10_000.0) < 4.0);
        assert!(cal.current_ma(N20_IDEAL + 10_000.0) > 20.0);
        // Код 0 (тока нет вообще) → примерно 0 мА.
        assert!(cal.current_ma(0.0).abs() < 1e-2);
    }
}