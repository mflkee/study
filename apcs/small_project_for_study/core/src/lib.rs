//! Мини-полигон: кнопка + светодиод по Modbus RTU.
//!
//! Это **чистое ядро** — без железа и без ESP-IDF. Вся «логика» проекта
//! живёт здесь и проверяется обычными `cargo test` на любом ПК:
//!
//! ```text
//! cd core && cargo test
//! ```
//!
//! (Прошивка `../fw` — тонкая обвязка, которая только подключает GPIO/UART
//! и вызывает функции этого крейта.)
//!
//! # Что «умеет» мини-полигон
//!
//! Физически это кнопка + светодиод. Наружу — Modbus RTU slave с такой
//! картой адресов:
//!
//! | Адрес | Тип    | Что                          | Чтение | Запись |
//! |-------|--------|------------------------------|--------|--------|
//! | 0     | COIL   | светодиод (вкл/выкл)        | FC01   | FC05   |
//! | 1     | COIL   | кнопка (нажата ли сейчас)   | FC01   | —      |
//! | 0     | HOLDING| счётчик нажатий             | FC03   | —      |
//!
//! Секрет в том, что «железная» часть — крошечная:
//! кнопку и светодиод ведёт прошивка `../fw`, а ядро только хранит
//! состояние (`[registers::MiniState]`) и слушает Modbus-запросы.

pub mod crc;
pub mod debounce;
pub mod registers;

pub use registers::{dispatch, MiniState, SLAVE_ID};