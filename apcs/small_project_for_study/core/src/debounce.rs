//! Антидребезг кнопки — фильтр «N одинаковых отсчётов подряд».
//!
//! # Зачем нужен
//!
//! Механические контакты при нажатии «звенят»: в течение десятка миллисекунд
//! уровень пинa несколько раз дёргается `0/1/0/1…`, прежде чем стабилизируется.
//! Если читать кнопку «в лоб», один клик превратится в десятки нажатий.
//!
//! Классический простейший фильтр — **«N одинаковых отсчётов подряд»**:
//! каждую итерацию опроса сравниваем новое значение с устоявшимся;
//! только когда N прочитанных значений совпали и отличаются от текущего
//! состояния — переключаем состояние.
//!
//! # Почему это «core», а не прошивка
//!
//! Дребезг — чисто логический процесс (счётчики+сравнение), железу про него
//! знать не нужно. Поэтому алгоритм живёт здесь, в тестируемом крейте,
//! а `fw` только кормит его сырыми отсчётами GPIO раз в `POLL_MS`.

/// Целочисленный фильтр «N одинаковых отсчётов подряд».
#[derive(Debug, Clone)]
pub struct Debounce {
    /// Установившееся значение (считается «истинным»).
    stable: bool,
    /// Сколько отсчётов подряд мы видим значение, отличное от `stable`.
    pending: u32,
}

impl Debounce {
    /// Сколько одинаковых отсчётов подряд нужно, чтобы сменить состояние.
    pub const SAMPLES: u32 = 5;

    /// Создаёт фильтр, начав с известного уровня контакта.
    pub fn new(initial: bool) -> Self {
        Self {
            stable: initial,
            pending: 0,
        }
    }

    /// Скормить очередной сырой отсчёт. Возвращает устоявшийся уровень.
    pub fn feed(&mut self, raw: bool) -> bool {
        if raw == self.stable {
            // Значение совпало с устоявшимся — «дребезг» прервался.
            self.pending = 0;
        } else {
            // Отличается: копим «подозрительные» совпадения.
            self.pending = self.pending.saturating_add(1);
            if self.pending >= Self::SAMPLES {
                self.stable = raw;
                self.pending = 0;
            }
        }
        self.stable
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Что выходит из фильтра, когда кнопку нажали и держат.
    #[test]
    fn clean_press_advances_after_n_samples() {
        let mut d = Debounce::new(false);
        // Первые N-1 совпадений ещё «читаются» как прежнее значение...
        for _ in 0..Debounce::SAMPLES - 1 {
            assert!(!d.feed(true), "нажатие ещё не подтверждено");
        }
        // ...а на N-м — переключается.
        assert!(d.feed(true));
    }

    /// Один короткий всплеск (дребезг) не должен зажать кнопку.
    #[test]
    fn single_glitch_is_ignored() {
        let mut d = Debounce::new(false);
        assert!(!d.feed(true)); // один чужой отсчёт
        assert!(!d.feed(false));
        assert!(!d.feed(false));
        assert!(!d.feed(false));
        // Устоялось в «не нажато».
    }

    /// Полный цикл «нажали → отпустили» даёт переключение в обе стороны.
    #[test]
    fn press_release_roundtrip() {
        let mut d = Debounce::new(false);
        for _ in 0..Debounce::SAMPLES {
            d.feed(true);
        }
        assert!(d.feed(true));
        for _ in 0..Debounce::SAMPLES {
            d.feed(false);
        }
        assert!(!d.feed(false));
    }
}